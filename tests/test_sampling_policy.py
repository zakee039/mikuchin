"""Mikuchin UI is the single source of thinking budget; PolyStrata only guards loops."""
from __future__ import annotations
import json
import os
import re
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JS = (ROOT / "frontend/web/app.js").read_text(encoding="utf-8")
POLY = ROOT / "backend/polystrata"
sys.path.insert(0, str(POLY))


def between(start, end):
    a = JS.index(start)
    return JS[a:JS.index(end, a)]


class SamplingPolicy(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        import shutil
        if not shutil.which("node"):
            raise unittest.SkipTest("node is unavailable")

    def js(self, code):
        p = subprocess.run(["node", "-e", code], cwd=ROOT, capture_output=True, text=True, timeout=20)
        self.assertEqual(p.returncode, 0, p.stderr)
        return json.loads(p.stdout)

    def test_ui_budget_controls_every_request_and_shared_default(self):
        helpers = between("const THINKING_BUDGET_TOKENS", "// Migrate the former implicit High default once")
        shared = between("function sharedDefaults(s)", "async function saveShared")
        request = re.search(r"const body = \{model: health\.model,[\s\S]*?\};", JS)
        self.assertIsNotNone(request)
        code = (helpers + "\nfunction projectionLoaded() { return false; }\n" + shared +
                "const health={model:'sample'}; const assembledMessages=[];" +
                "const output=['none','low','medium','high'].map(thinking => {" +
                "const settings={...DEFAULTS,thinking};" + request.group(0) +
                "return {thinking, body:body.reasoning_budget_tokens, shared:sharedDefaults(settings)};});" +
                "console.log(JSON.stringify(output));")
        rows = self.js(code)
        expected = {'none': 0, 'low': 1024, 'medium': 4096, 'high': 16388}
        self.assertEqual({r['thinking']:r['body'] for r in rows}, expected)
        for r in rows:
            self.assertEqual(r['shared']['reasoning_budget_tokens'], expected[r['thinking']])
            self.assertEqual(r['shared']['reasoning_effort'], r['thinking'])

    def test_defaults_and_auto_sync_are_on(self):
        self.assertRegex(JS, r'DEFAULTS = \{thinking: "low"')
        self.assertIn('store.get("sampling-share-enabled", true) !== false', JS)
        self.assertIn('await saveShared(true, settings)', JS)
        self.assertIn('.then(loadShared)', JS)
        self.assertIn('store.set("sampling-share-enabled", share)', JS)
        self.assertIn('store.get("thinking-budgets-v1", false)', JS)
        index = (ROOT / 'frontend/web/index.html').read_text('utf8')
        self.assertIn('id="s-share" role="switch" aria-checked="true"', index)
        self.assertIn('thinking + answer; empty = no extra limit', index)

    def test_backend_has_no_extra_budget_but_loop_guard_defaults_on(self):
        from serve.server import model_settings
        active_path = ROOT / 'config/active.json'  # runtime-only, intentionally Git-ignored
        if active_path.exists():
            active = json.loads(active_path.read_text('utf8'))
            self.assertNotIn('reasoning_budget_tokens', active)
            self.assertEqual(active.get('reasoning_loop_recovery'), 'stop')
            self.assertEqual(active.get('reasoning_effort'), 'low')
            self.assertEqual(model_settings(active)['reasoning_budget_tokens'], 0)
        self.assertEqual(model_settings({})['reasoning_budget_tokens'], 0)
        env = os.environ.get('MIKUCHIN_WEB_DIR')
        try:
            os.environ['MIKUCHIN_WEB_DIR'] = str(ROOT/'frontend/web')
            self.assertEqual(model_settings({'exe':'stub'})['reasoning_loop_recovery'], 'stop')
            self.assertEqual(model_settings({'reasoning_loop_recovery':False})['reasoning_loop_recovery'],False)
            os.environ.pop('MIKUCHIN_WEB_DIR', None)
            self.assertFalse(model_settings({})['reasoning_loop_recovery'])
        finally:
            if env is None:os.environ.pop('MIKUCHIN_WEB_DIR',None)
            else:os.environ['MIKUCHIN_WEB_DIR']=env

    def test_initial_shared_defaults_are_ui_derived(self):
        path = ROOT / 'config/active.shared-settings.json'  # generated by first sync, not tracked
        if not path.exists():
            self.skipTest('no local shared-settings file (clean clone)')
        shared = json.loads(path.read_text('utf8'))
        self.assertEqual(shared['reasoning_effort'], 'low')
        self.assertEqual(shared['reasoning_budget_tokens'], 1024)
        active = ROOT / 'config/active.json'
        if active.exists():
            self.assertNotIn('reasoning_budget_tokens', json.loads(active.read_text('utf8')))

if __name__ == '__main__':
    unittest.main()
